"""Run every case_studies/*.sql file against the dbt-built DuckDB and save each query's result as Markdown.

Queries inside a file are separated by `;` and titled with a `-- name: <title>` comment.
Usage (after `dbt build`):  python scripts/run_case_studies.py
"""
from pathlib import Path
import re

import duckdb

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = ROOT / "olist.duckdb"
CASE_DIR = ROOT / "case_studies"
OUT_DIR = CASE_DIR / "results"


def to_markdown(columns, rows):
    def fmt(value):
        if value is None:
            return ""
        if isinstance(value, float):
            return f"{value:,.2f}".rstrip("0").rstrip(".")
        if isinstance(value, int):
            return f"{value:,}"
        return str(value)

    header = "| " + " | ".join(columns) + " |"
    divider = "| " + " | ".join("---" for _ in columns) + " |"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join([header, divider, *body])


def split_queries(sql_text):
    for chunk in sql_text.split(";"):
        if not chunk.strip():
            continue
        match = re.search(r"--\s*name:\s*(.+)", chunk)
        title = match.group(1).strip() if match else "Result"
        yield title, chunk


def main():
    OUT_DIR.mkdir(exist_ok=True)
    con = duckdb.connect(str(DB_PATH), read_only=True)
    for sql_file in sorted(CASE_DIR.glob("*.sql")):
        sections = [f"# Results: {sql_file.stem}", "", f"Generated by `scripts/run_case_studies.py` from `{sql_file.name}`.", ""]
        for title, query in split_queries(sql_file.read_text(encoding="utf-8")):
            cursor = con.execute(query)
            columns = [d[0] for d in cursor.description]
            sections += [f"## {title}", "", to_markdown(columns, cursor.fetchall()), ""]
        out_file = OUT_DIR / f"{sql_file.stem}.md"
        out_file.write_text("\n".join(sections), encoding="utf-8")
        print(f"wrote {out_file.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
